from enum import Enum
class Role(str, Enum):
    admin = 'admin'
    analyst = 'analyst'
    viewer = 'viewer'
class JobStatus(str, Enum):
    queued = 'queued'
    running = 'running'
    completed = 'completed'
    failed = 'failed'
class PartKind(str, Enum):
    machine = 'machine'
    assembly = 'assembly'
    component = 'component'
class RecallStatus(str, Enum):
    tracing = 'tracing'
    open = 'open'
    closed = 'closed'
class IsolationStatus(str, Enum):
    isolated = 'isolated'
    released = 'released'
